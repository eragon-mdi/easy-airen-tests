// Package search — быстрый in-memory поиск документов по словам с допуском
// опечаток и поиском по части слова.
//
// Как это работает:
//  1. При построении индекса текст каждого документа нормализуется и режется
//     на слова. Строится словарь уникальных слов, для каждого слова —
//     набор n-грамм (по умолчанию триграмм) и список документов, где оно есть.
//  2. При поиске каждое слово запроса сравнивается со ВСЕМ словарём
//     (это тысячи дешёвых сравнений, а не проход по всем документам).
//     Схожесть слов — коэффициент Дайса по n-граммам плюс бонус, если слово
//     из запроса является началом или частью слова из словаря.
//  3. Оценки подходящих слов раздаются документам через инвертированный
//     индекс; оценка документа — сумма лучших совпадений по словам запроса.
//  4. Документы сортируются по убыванию оценки, возвращаются первые limit.
package search

// Document — то, что индексируется. ID выбирает вызывающая сторона
// (например, ID вопроса); повторяющиеся тексты допустимы — это разные
// документы с разными ID.
type Document struct {
	ID   int
	Text string
}

// Result — найденный документ и его оценка (больше — релевантнее).
type Result struct {
	ID    int
	Score float64
}

// Searcher — контракт поиска. Потребители зависят от интерфейса,
// а не от конкретной реализации индекса.
type Searcher interface {
	// Search возвращает до limit самых похожих документов по убыванию оценки.
	// limit <= 0 означает «без ограничения». Пустой запрос даёт пустой результат.
	Search(query string, limit int) []Result
}
